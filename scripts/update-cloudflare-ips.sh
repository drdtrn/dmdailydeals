#!/bin/sh
# Regenerate caddy/cloudflare-ips.caddy from Cloudflare's published ranges.
#   sh scripts/update-cloudflare-ips.sh && docker compose ... exec caddy caddy reload --config /etc/caddy/Caddyfile
# Cloudflare changes these lists rarely (announced at https://www.cloudflare.com/ips/).
set -eu
out="${1:-$(dirname "$0")/../caddy/cloudflare-ips.caddy}"
v4=$(curl -fsS https://www.cloudflare.com/ips-v4)
v6=$(curl -fsS https://www.cloudflare.com/ips-v6)
[ -n "$v4" ] && [ -n "$v6" ] || { echo "empty IP list, not writing" >&2; exit 1; }
ranges=$(printf '%s\n%s\n' "$v4" "$v6" | tr '\n' ' ' | sed 's/ *$//')
cat > "$out" <<EOT
# Generated by scripts/update-cloudflare-ips.sh on $(date -u +%Y-%m-%d). Do not edit by hand.
# Source: https://www.cloudflare.com/ips-v4 and https://www.cloudflare.com/ips-v6
(cloudflare_ranges) {
	$ranges
}

# Anyone who is not Cloudflare gets the connection dropped. CF-Connecting-IP is trusted for rate
# limiting, so it must not be forgeable: the origin must not be reachable except through Cloudflare.
# ALLOW_EXTRA_CIDRS (default: loopback only) is for local rehearsals; leave it unset in production.
# remote_ip does not accept a block, so the ranges are repeated inline here.
(cloudflare_only) {
	@not_cloudflare not remote_ip {\$ALLOW_EXTRA_CIDRS:127.0.0.1/32} $ranges
	abort @not_cloudflare
}
EOT
echo "wrote $out"

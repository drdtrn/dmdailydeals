import { z } from 'zod'

import { findFirstPersonClaims } from './firstPerson'

/**
 * The output the writing step must produce, and the rules a draft must pass before it is saved.
 * Everything here is pure (no I/O): the task fetches the inventory and the existing slugs first and
 * passes them in through `DraftContext`.
 */

export const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/

export const draftSchema = z.object({
  title: z.string().min(10).max(120),
  slug: z.string().min(3).max(90).regex(SLUG_RE, 'must be lowercase words joined by hyphens'),
  metaTitle: z.string().min(10).max(70),
  metaDescription: z.string().min(50).max(170),
  outline: z.array(z.string().min(2)).min(3).max(20),
  bodyMarkdown: z.string().min(200),
  sources: z
    .array(z.object({ title: z.string().min(1), url: z.string().url() }))
    .min(1)
    .max(20),
  internalLinks: z.array(z.object({ anchor: z.string().min(1), url: z.string().min(1) })).max(12),
  suggestedRelatedDealIds: z.array(z.number().int()).max(8),
})
export type DraftOutput = z.infer<typeof draftSchema>

export type InventoryItem = {
  /** Root-relative path, e.g. "/deal/some-slug". */
  url: string
  label: string
  kind: 'deal' | 'category' | 'drop' | 'page' | 'post'
  /** Present for deals: the id the model may list in `suggestedRelatedDealIds`. */
  id?: number
}

export type DraftContext = {
  /** The site origin, so an absolute link to our own pages is understood as internal. */
  origin: string
  targetWords: number
  inventory: readonly InventoryItem[]
  /** Every URL the search tool returned in this run. */
  researchedUrls: readonly string[]
  /** Slugs of existing posts (any status). */
  takenSlugs: ReadonlySet<string>
  /** Root-relative URLs the brief says must be linked. */
  mustLinkUrls: readonly string[]
  experienceSource: 'human' | 'ai'
}

/** Allowed distance from the target word count. */
export const WORD_COUNT_TOLERANCE = 0.2

/**
 * One form per URL so two spellings of the same page compare equal. Our own pages become
 * root-relative ("/deal/x"); other URLs lose their fragment and trailing slash and get a
 * lower-case host.
 */
export function normalizeUrl(raw: string, origin: string): string {
  const url = raw.trim()
  const base = origin.replace(/\/+$/, '')
  let rest = url
  if (base && url.toLowerCase().startsWith(`${base.toLowerCase()}/`)) rest = url.slice(base.length)
  else if (base && url.toLowerCase() === base.toLowerCase()) rest = '/'

  if (rest.startsWith('/')) {
    const path = rest.split('#')[0]
    return path.length > 1 ? path.replace(/\/+$/, '') : path
  }
  try {
    const parsed = new URL(url)
    parsed.hash = ''
    const out = `${parsed.protocol}//${parsed.host.toLowerCase()}${parsed.pathname.replace(/\/+$/, '')}${parsed.search}`
    return out
  } catch {
    return url
  }
}

const MARKDOWN_LINK_RE = /\[([^\]]*)\]\(\s*([^)\s]+)(?:\s+"[^"]*")?\s*\)/g

/** The `[anchor](url)` links of a markdown body. */
export function extractMarkdownLinks(markdown: string): { anchor: string; url: string }[] {
  return [...markdown.matchAll(MARKDOWN_LINK_RE)].map((m) => ({ anchor: m[1], url: m[2] }))
}

/** Words as a reader counts them: link syntax, heading marks and list markers don't count. */
export function countWords(markdown: string): number {
  const text = markdown
    .replace(MARKDOWN_LINK_RE, '$1')
    .replace(/^[ \t]*(?:#{1,6}|[-*+]|\d+[.)])[ \t]+/gm, '')
    .replace(/[*_`>~]/g, '')
  return text.split(/\s+/).filter((word) => /[\p{L}\p{N}]/u.test(word)).length
}

const AI_STATEMENT_RE =
  /\b(?:as an ai\b|ai[- ]generated|generated by (?:an? )?(?:ai|model|language model)|written by (?:an? )?(?:ai|model)|(?:a |an )?(?:large )?language model|chatgpt|deepseek|openai|this (?:article|guide|post) was (?:written|generated|produced))/i

/** Every problem with a draft, as short sentences the model can act on. Empty when it is fine. */
export function validateDraft(draft: DraftOutput, ctx: DraftContext): string[] {
  const problems: string[] = []
  const norm = (u: string) => normalizeUrl(u, ctx.origin)

  const inventoryUrls = new Set(ctx.inventory.map((i) => norm(i.url)))
  const researched = new Set(ctx.researchedUrls.map(norm))
  const sourceUrls = new Set(draft.sources.map((s) => norm(s.url)))

  // Slug
  if (ctx.takenSlugs.has(draft.slug)) {
    problems.push(`slug "${draft.slug}" is already used by another post; choose a different one`)
  }

  // Sources must come from the research
  for (const source of draft.sources) {
    if (!researched.has(norm(source.url))) {
      problems.push(
        `source ${source.url} was not among the researched URLs; list only pages from the research`,
      )
    }
  }

  // Internal links must come from the inventory
  for (const link of draft.internalLinks) {
    if (!inventoryUrls.has(norm(link.url))) {
      problems.push(`internalLinks url ${link.url} is not in the link inventory`)
    }
  }

  // Every link in the body is either an inventory page or one of the listed sources
  for (const link of extractMarkdownLinks(draft.bodyMarkdown)) {
    const url = norm(link.url)
    if (!inventoryUrls.has(url) && !sourceUrls.has(url)) {
      problems.push(
        `the body links to ${link.url}, which is neither in the link inventory nor in sources`,
      )
    }
  }

  // Required links
  const bodyLinks = new Set(extractMarkdownLinks(draft.bodyMarkdown).map((l) => norm(l.url)))
  for (const must of ctx.mustLinkUrls) {
    if (!bodyLinks.has(norm(must))) problems.push(`the body must link to ${must}`)
  }

  // Related deals must exist in the inventory
  const dealIds = new Set(ctx.inventory.filter((i) => i.kind === 'deal').map((i) => i.id))
  for (const id of draft.suggestedRelatedDealIds) {
    if (!dealIds.has(id))
      problems.push(`suggestedRelatedDealIds contains ${id}, which is not a deal in the inventory`)
  }

  // Length
  const words = countWords(draft.bodyMarkdown)
  const min = Math.ceil(ctx.targetWords * (1 - WORD_COUNT_TOLERANCE))
  const max = Math.floor(ctx.targetWords * (1 + WORD_COUNT_TOLERANCE))
  if (words < min || words > max) {
    problems.push(
      `the body has ${words} words; it must be between ${min} and ${max} (target ${ctx.targetWords})`,
    )
  }

  // House rules
  if (/^#\s/m.test(draft.bodyMarkdown)) {
    problems.push(
      'the body must not contain a "# " heading; the title is the page heading (use "## ")',
    )
  }
  if (/^#{2,4}\s*(?:faq\b|frequently asked|people also ask)/im.test(draft.bodyMarkdown)) {
    problems.push('remove the FAQ section; no FAQ-style blocks')
  }
  if (AI_STATEMENT_RE.test(`${draft.title}\n${draft.bodyMarkdown}`)) {
    problems.push('remove any statement about how the guide was produced')
  }
  if (ctx.experienceSource === 'ai') {
    const claims = findFirstPersonClaims(draft.bodyMarkdown)
    if (claims.length > 0) {
      problems.push(
        `remove first-person usage claims (${claims
          .slice(0, 3)
          .map((c) => `"${c}"`)
          .join(', ')}); write in the second person or neutrally`,
      )
    }
  }
  return problems
}
